"""DEPTHOPEN G-smoke and G-grad — can this box train an arm, and does the gate actually receive gradient?

SPEC §5's two gates before the freeze, in one job, on arm A3 (the primary treatment):

  G-smoke   50 training steps on the instance: peak memory under 46 GB, seconds per step recorded, loss
            decreasing, checkpoint saved and reloadable through `predict_action`.
  G-grad    the gate parameters receive nonzero gradient under LoRA mode and sit in an optimizer group;
            72 gate tensors have `requires_grad` for a per-layer gated arm.
  D-6       SPEC §4's pre-training check: the depth companions agree with the released fine-tune's own
            predicted grid on the same frames, against a shuffled null.

Both are realized measurements, not readings of intent: the gradient comes from a hook on the gate
parameters during the real backward pass, and the reload runs the exported checkpoint through this
study's own Actor on a frame from POSTCHECK's rendered pack.

The batch size is measured rather than assumed. Short probe runs at increasing `device_batch_size` record
peak memory and seconds per step; the largest that fits becomes the arms' batch, and the number is banked
so every arm afterwards trains on the same one.

  pg run infra.aws_pg.jobs.depthopen_smoke --type g6e.2xlarge \\
     --weights models--allenai--MolmoAct2-Think,models--allenai--MolmoAct2-Think-LIBERO,models--allenai--MolmoAct-7B-D-0812 \\
     --s3-prefix results/depthopen/smoke/1 --budget-min 240 --args " --probe-batches 1,2"
"""
from __future__ import annotations

import os

os.environ["HF_HUB_OFFLINE"] = "0"
os.environ.pop("TRANSFORMERS_OFFLINE", None)
os.environ.setdefault("HF_HUB_DISABLE_XET", "1")

import argparse
import json
import pathlib
import sys
import time
from typing import Dict, List, Optional

import numpy as np

from infra.aws_pg.jobs.postcheck_files import Bank
from infra.pg import depthopen_train as dt

MEMORY_CAP_GB = 46.0          # SPEC §5 G-smoke
EXPECTED_GATE_TENSORS = 72    # 36 per-layer heads, weight and bias each


def stage_stack(bank: Bank, work: pathlib.Path) -> pathlib.Path:
    t0 = time.perf_counter()
    src = dt.fetch_source(work)
    bank.stage("source", {"root": str(src), "sha": dt.MO2_SHA,
                          "seconds": round(time.perf_counter() - t0, 1)})
    installed = dt.install_stack(src)
    bank.stage("install", installed)
    print(f"[install] {installed['n_installed']} packages added; torch={installed['torch']} "
          f"transformers={installed['transformers']} peft={installed['peft']}", flush=True)
    return src


def _snapshot_dir(repo: str) -> pathlib.Path:
    root = pathlib.Path(os.environ.get("HF_HOME", "/opt/hf-cache/hf")) / "hub"
    d = root / ("models--" + repo.replace("/", "--"))
    snaps = sorted((d / "snapshots").glob("*")) if (d / "snapshots").is_dir() else []
    if not snaps:
        raise FileNotFoundError(f"no restored snapshot for {repo} under {root}")
    return snaps[-1]


def stage_d6(bank: Bank, work: pathlib.Path, data: Dict[str, object], *, n_frames: int = 4,
             repo: str = "allenai/MolmoAct2-Think-LIBERO") -> Dict[str, object]:
    """SPEC §4's pre-training check: are the depth companions the same object the released fine-tune
    predicts on the same frame?

    The companions are generated by the makers' own script, so this is not a check of the arithmetic —
    it is a check that the pipeline was pointed at the right images, in the right orientation, with the
    right VAE. A wrong orientation or a stale VAE would still produce a well-formed 100-code grid, and
    training would then optimize against a prefix the released codebook does not mean. The null is the
    same comparison with the companion codes shuffled, which is DEPTHANCHOR's G1 control.
    """
    import pyarrow.parquet as pq
    import torch
    from transformers import AutoModelForImageTextToText, AutoProcessor
    from infra.pg import depthanchor_model as dam
    from infra.pg import depthopen_subset as ds

    # cv2 is not on the AMI; DEPTHANCHOR's loader installs it, and this stage decodes parquet images
    # BEFORE it touches the depth refs, so the install has to be asked for explicitly
    cv2_note = dam._ensure_cv2()

    data_root = pathlib.Path(str(data["data_root"])) / dt.SUBSET_REPO
    depth_root = pathlib.Path(str(data["depth_root"])) / dt.SUBSET_REPO
    first = sorted((data_root / "data" / "chunk-000").glob("*.parquet"))[0]
    tasks = {int(r["task_index"]): r["task"]
             for r in pq.read_table(data_root / ds.META_TASKS).to_pylist()}
    table = pq.read_table(first, columns=["episode_index", "frame_index", "task_index",
                                          "observation.images.image", "observation.images.wrist_image",
                                          "observation.state"])
    depth = pq.read_table(depth_root / first.relative_to(data_root),
                          columns=["episode_index", "frame_index", "depth_codes"])
    rows = table.to_pylist()
    dcodes = {(int(r["episode_index"]), int(r["frame_index"])): r["depth_codes"]
              for r in depth.to_pylist()}

    import cv2

    def _img(cell):
        raw = np.frombuffer(ds._img_bytes(cell), dtype=np.uint8)
        bgr = cv2.imdecode(raw, cv2.IMREAD_COLOR)
        return cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB)

    root = pathlib.Path(os.environ.get("HF_HOME", "/opt/hf-cache/hf")) / "hub"
    d = root / ("models--" + repo.replace("/", "--"))
    snaps = sorted((d / "snapshots").glob("*")) if (d / "snapshots").is_dir() else []
    if not snaps:
        raise FileNotFoundError(f"no restored snapshot for {repo} under {root}; sync it with --weights")
    processor = AutoProcessor.from_pretrained(str(snaps[-1]), trust_remote_code=True)
    model = AutoModelForImageTextToText.from_pretrained(str(snaps[-1]), trust_remote_code=True,
                                                        dtype=torch.float32).to("cuda").eval()
    dam.NORM_TAG = "libero"
    actor = dam.Actor(model, processor, enable_cuda_graph=False)
    refs = dam.load_depth_refs("cuda")

    from infra.pg import depthanchor_core as core     # its own Spearman, no scipy on the AMI
    out = []
    step = max(1, len(rows) // max(1, n_frames))
    for r in rows[::step][:n_frames]:
        key = (int(r["episode_index"]), int(r["frame_index"]))
        companion = np.asarray(dcodes[key], dtype=np.int64)
        frame = {"agentview": _img(r["observation.images.image"]),
                 "wrist": _img(r["observation.images.wrist_image"]),
                 "state": np.asarray(r["observation.state"], dtype=np.float32),
                 "task": tasks[int(r["task_index"])]}
        res = actor.natural(frame, seed=0)
        predicted = np.asarray(res.bins, dtype=np.int64)
        dc, dp = refs.cell_depths(companion), refs.cell_depths(predicted)
        rho = float(core.spearman(dc, dp))
        rng = np.random.default_rng(20260909 + key[1])
        null = float(core.spearman(refs.cell_depths(rng.permutation(companion)), dp))
        out.append({"episode": key[0], "frame": key[1],
                    "exact_code_match_fraction": float(np.mean(companion == predicted)),
                    "spearman_companion_vs_model": rho, "spearman_shuffled_null": null,
                    "n_grid_tokens": int(res.n_grid_tokens)})
        print(f"[d6] {key}: rho={rho:.3f} null={null:.3f} "
              f"exact={out[-1]['exact_code_match_fraction']:.3f}", flush=True)
    med = float(np.median([o["spearman_companion_vs_model"] for o in out]))
    med_null = float(np.median([abs(o["spearman_shuffled_null"]) for o in out]))
    payload = {"repo": repo, "cv2": cv2_note, "n_frames": len(out), "per_frame": out,
               "median_spearman": med, "median_abs_shuffled_null": med_null,
               "bar": 0.55,
               "passes": bool(med > 0.55 and med > med_null),
               "why": ("SPEC §4: the companion grid must agree with the released fine-tune's own "
                       "predicted grid above DEPTHANCHOR's G1 bar, against a shuffled null")}
    bank.stage("d6", payload)
    print(f"[d6] median rho {med:.3f} against null {med_null:.3f}: passes={payload['passes']}",
          flush=True)
    import gc
    del actor, model, processor, refs      # the actor holds the model; dropping only `model` frees nothing
    gc.collect()
    torch.cuda.empty_cache()
    print(f"[d6] freed; cuda reserved now {torch.cuda.memory_reserved() / 1e9:.1f} GB", flush=True)
    return payload


def stage_probe_batches(bank: Bank, src: pathlib.Path, work: pathlib.Path, data: Dict[str, object],
                        batches: List[int], steps: int, seed: int) -> Dict[str, object]:
    """The largest `device_batch_size` that fits, measured. An OOM here is a result, not a crash: it is
    recorded and the next batch is not tried."""
    results = []
    chosen = None
    for b in batches:
        save = work / f"probe_b{b}"
        log = work / f"probe_b{b}.log"
        argv = dt.train_argv("A3", steps=steps, device_batch=b, global_batch=b,
                             save_folder=save, seed=seed, save_checkpoints=False)
        print(f"[probe] device_batch_size={b}, {steps} steps", flush=True)
        t0 = time.perf_counter()
        try:
            run = dt.run_training(src, work, argv, data=data, log_path=log,
                                  artifact_dir=bank.out)
        except RuntimeError as exc:
            text = str(exc)
            # torchrun's summary hides the child's error, so the cause is read from the banked training
            # log — that is where "CUDA out of memory" or a collator ValueError actually appears
            trainlog = bank.out / f"trainlog_{log.stem}.log"
            body = trainlog.read_text()[-20000:] if trainlog.is_file() else ""
            oom = any(k in (text + body) for k in ("CUDA out of memory", "OutOfMemoryError",
                                                   "CUDA error: out of memory"))
            cause = next((line for line in reversed(body.splitlines())
                          if line.strip().startswith(("ValueError", "RuntimeError", "TypeError",
                                                      "KeyError", "AssertionError"))), "")
            results.append({"device_batch_size": b, "fits": False, "oom": oom,
                            "cause": cause[:300] or "see the banked training log",
                            "seconds": round(time.perf_counter() - t0, 1),
                            "why": text[-2000:]})
            bank.stage("probe_batches", {"results": results})
            print(f"[probe] batch {b} failed: oom={oom} cause={cause[:200]}", flush=True)
            if chosen is not None:
                # a smaller batch already worked, so the largest that fits is known and the arms can run;
                # the failure is recorded either way
                break
            raise
        probe = run.get("grad_probe") or {}
        results.append({"device_batch_size": b, "fits": True,
                        "seconds_per_step": run.get("seconds_per_step"),
                        "n_step_lines": run["n_step_lines"],
                        "peak_allocated_gb": probe.get("cuda_max_memory_allocated_gb"),
                        "peak_reserved_gb": probe.get("cuda_max_memory_reserved_gb"),
                        "seconds": run["seconds"]})
        chosen = b
        bank.stage("probe_batches", {"results": results, "chosen": chosen})
    if chosen is None:
        raise RuntimeError(f"no device_batch_size fits: {results}")
    out = {"results": results, "chosen_device_batch_size": chosen}
    bank.stage("probe_batches", out)
    return out


def stage_smoke(bank: Bank, src: pathlib.Path, work: pathlib.Path, data: Dict[str, object],
                *, steps: int, device_batch: int, global_batch: int, seed: int) -> Dict[str, object]:
    save = work / "smoke_A3"
    log = work / "smoke_A3.log"
    argv = dt.train_argv("A3", steps=steps, device_batch=device_batch, global_batch=global_batch,
                         save_folder=save, seed=seed)

    def on_line(step, line):
        if step["step"] % 10 == 0:
            bank.stage("smoke_progress", step)
            print(f"[smoke] {step}", flush=True)

    run = dt.run_training(src, work, argv, data=data, log_path=log,
                          artifact_dir=bank.out, on_line=on_line)
    listing = dt.checkpoint_listing(save)
    probe = run.get("grad_probe") or {}
    payload = {
        "arm": "A3", "steps": steps, "device_batch_size": device_batch,
        "global_batch_size": global_batch, "seed": seed,
        "seconds": run["seconds"], "seconds_per_step": run.get("seconds_per_step"),
        "loss_first_half_mean": run.get("loss_first_half_mean"),
        "loss_second_half_mean": run.get("loss_second_half_mean"),
        "loss_decreasing": run.get("loss_decreasing"),
        "peak_allocated_gb": probe.get("cuda_max_memory_allocated_gb"),
        "peak_reserved_gb": probe.get("cuda_max_memory_reserved_gb"),
        "checkpoint_dirs": listing,
        "save_folder": str(save),
    }
    bank.artifact("smoke_steps.json", run["steps"])
    bank.stage("smoke", payload)
    return {**payload, "grad_probe": probe, "save_folder": save}


def stage_g_grad(bank: Bank, probe: Dict[str, object],
                 moved: Optional[Dict[str, object]] = None) -> Dict[str, object]:
    """G-grad, read from the hook record: how many gate tensors were trainable, which optimizer group
    held them, and the largest gradient norm each one saw."""
    # `get_param_groups` is called more than once per run, so the record holds each tensor twice —
    # measured: 144 entries for 36 per-layer heads. Dedupe by name before counting anything.
    seen: Dict[str, Dict[str, object]] = {}
    for e in probe.get("gate_params", []):
        seen.setdefault(e["name"], e)
    entries = list(seen.values())
    names = [e["name"] for e in entries]
    trainable = [e for e in entries if e["requires_grad"]]
    grads = probe.get("grad_norms", {})
    nonzero = {k: v for k, v in grads.items() if v and v > 0}
    groups = sorted(set(probe.get("group_of", {}).values()))
    verdict = {
        "n_gate_tensors": len(names),
        "n_gate_trainable": len(trainable),
        "expected_trainable": EXPECTED_GATE_TENSORS,
        "trainable_matches_expected": len(trainable) == EXPECTED_GATE_TENSORS,
        "optimizer_groups_holding_the_gate": groups,
        "in_action_expert_group": groups == ["action_expert"],
        "n_gate_params_with_nonzero_grad": len(nonzero),
        "grad_norm_min": round(min(nonzero.values()), 8) if nonzero else 0.0,
        "grad_norm_max": round(max(nonzero.values()), 8) if nonzero else 0.0,
        "example_names": names[:4],
        "init_value_mean": (round(float(np.mean([e["value_mean"] for e in probe["gate_params"]
                                                if e["name"].endswith("bias")])), 6)
                            if probe.get("gate_params") else None),
    }
    # The per-parameter hooks record nothing under FSDP — the gradient lands on a flat parameter, not on
    # the leaves the hooks sit on (measured: 0 of 72 fired while training plainly worked). So the gradient
    # clause is read as a REALIZED update instead: did the gate's own tensors change between the base
    # checkpoint and this arm's export?
    verdict["gate_tensors_moved"] = (moved or {}).get("gate_tensors_moved")
    verdict["gate_max_abs_delta"] = (moved or {}).get("gate_max_abs_delta")
    verdict["hooks_fired"] = verdict["n_gate_params_with_nonzero_grad"]
    verdict["passes"] = bool(verdict["trainable_matches_expected"]
                             and verdict["in_action_expert_group"]
                             and (verdict["gate_tensors_moved"] or 0) > 0)
    bank.stage("g_grad", verdict)
    print(f"[g-grad] {json.dumps(verdict)[:400]}", flush=True)
    return verdict


def stage_export_and_reload(bank: Bank, src: pathlib.Path, work: pathlib.Path,
                            save_folder: pathlib.Path) -> Dict[str, object]:
    """The exported checkpoint must load and act. Anything less leaves R1-R4 unrunnable on the arms."""
    merged = sorted(save_folder.glob("step*-merged"))
    if not merged:
        raise RuntimeError(f"no merged checkpoint in {save_folder}: "
                           f"{sorted(p.name for p in save_folder.glob('*'))}")
    hf_dir = work / (merged[-1].name.replace("-merged", "-hf"))
    conv = dt.convert_to_hf(src, merged[-1], hf_dir, work=work)
    bank.stage("export", conv)
    print(f"[export] {conv['gate_in_config']}", flush=True)

    # reload through this study's own instruments, on a frame from POSTCHECK's rendered pack
    from infra.aws_pg.jobs.postcheck_render import load_frames
    frames_dir = work / "frames"
    frames_dir.mkdir(parents=True, exist_ok=True)
    dt.s3("cp", f"s3://{dt.BUCKET}/postcheck/frames/v1/frames.npz", str(frames_dir / "frames.npz"))
    dt.s3("cp", f"s3://{dt.BUCKET}/postcheck/frames/v1/frames_index.json",
          str(frames_dir / "frames_index.json"))
    frames = load_frames(frames_dir)

    import torch
    from transformers import AutoModelForImageTextToText, AutoProcessor
    from infra.pg import depthanchor_model as dam
    processor = AutoProcessor.from_pretrained(str(hf_dir), trust_remote_code=True)
    model = AutoModelForImageTextToText.from_pretrained(str(hf_dir), trust_remote_code=True,
                                                        dtype=torch.float32).to("cuda").eval()
    actor = dam.Actor(model, processor, enable_cuda_graph=False)
    # POSTCHECK's weights-only reader, not `dam.gate_weights_readout`: the latter returned nulls for every
    # field on an exported checkpoint (present/per_layer only), so it said nothing about where the bias sat
    from infra.pg import postcheck_weights as pcw
    read = pcw.read_gate(hf_dir)
    gate = pcw.summarize(read, init_bias=float(dt.ARMS["A3"]["init_bias"]))
    res = actor.natural(frames[0], seed=0)
    a = np.asarray(res.a_norm)
    payload = {
        "hf_dir": str(hf_dir),
        "gate_after_50_steps": {k: gate.get(k) for k in
                                ("present", "n_layers", "bias_min", "bias_max", "sigmoid_min",
                                 "sigmoid_max", "max_abs_bias_deviation", "init_bias_declared",
                                 "verdict")},
        "action_shape": list(a.shape),
        "action_finite": bool(np.isfinite(a).all()),
        "action_abs_mean": float(np.abs(a).mean()),
        "n_grid_tokens": res.n_grid_tokens,
        "n_tail_tokens": res.n_tail_tokens,
        "gate_applied_mean": (None if res.gate is None else float(np.mean(res.gate))),
        "frame": {"task": frames[0]["task"], "spec": frames[0]["spec"]},
    }
    bank.stage("reload", payload)
    print(f"[reload] {json.dumps(payload, default=str)[:500]}", flush=True)
    del model
    torch.cuda.empty_cache()
    return payload


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--work", default="/work/depthopen")
    ap.add_argument("--probe-batches", default="1,2",
                    help="device_batch_size values to try, increasing")
    ap.add_argument("--probe-steps", type=int, default=8)
    ap.add_argument("--smoke-steps", type=int, default=50)
    ap.add_argument("--seed", type=int, default=20260909)
    ap.add_argument("--skip-probe", action="store_true")
    ap.add_argument("--skip-d6", action="store_true",
                    help="skip the companion-agreement check (it loads the released fine-tune)")
    ap.add_argument("--device-batch", type=int, default=0,
                    help="skip the probe and use this batch")
    args = ap.parse_args()
    work = pathlib.Path(args.work)
    work.mkdir(parents=True, exist_ok=True)
    bank = Bank(pathlib.Path(args.out), "depthopen_smoke")
    bank.top("args", vars(args))
    bank.top("pins", {"molmoact2_sha": dt.MO2_SHA, "base": dt.BASE_CKPT,
                      "subset_repo": dt.SUBSET_REPO, "arm": "A3", "arms": dt.ARMS})

    src = stage_stack(bank, work)
    data = dt.sync_data(work)
    bank.stage("data", data)
    print(f"[data] {json.dumps(data)}", flush=True)

    d6 = stage_d6(bank, work, data) if not args.skip_d6 else None

    batch = args.device_batch
    if not batch and not args.skip_probe:
        probe = stage_probe_batches(bank, src, work, data,
                                    [int(b) for b in args.probe_batches.split(",") if b.strip()],
                                    args.probe_steps, args.seed)
        batch = int(probe["chosen_device_batch_size"])
    batch = batch or 1

    smoke = stage_smoke(bank, src, work, data, steps=args.smoke_steps, device_batch=batch,
                        global_batch=batch, seed=args.seed)
    reload_ok = stage_export_and_reload(bank, src, work, smoke["save_folder"])
    base_snapshot = _snapshot_dir(dt.BASE_CKPT)
    moved = dt.weights_moved(base_snapshot, pathlib.Path(reload_ok["hf_dir"]))
    bank.stage("weights_moved", {k: v for k, v in moved.items() if k != "per_tensor"})
    bank.artifact("weights_moved.json", moved)
    g_grad = stage_g_grad(bank, smoke["grad_probe"], moved)

    peak = smoke.get("peak_reserved_gb") or smoke.get("peak_allocated_gb")
    g_smoke = {
        "peak_reserved_gb": peak,
        "under_cap": bool(peak is not None and peak < MEMORY_CAP_GB),
        "cap_gb": MEMORY_CAP_GB,
        "seconds_per_step": smoke.get("seconds_per_step"),
        "weights_moved": moved.get("passes"),
        "n_tensors_moved": f"{moved.get('n_moved')}/{moved.get('n_tensors_compared')}",
        "max_abs_delta_overall": moved.get("max_abs_delta_overall"),
        "loss_decreasing_not_readable": ("the trainer sends per-step loss to W&B only and this study runs "
                                         "with --wandb=null; replaced by the weights diff above"),
        "merged_checkpoint_written": any(k.endswith("-merged") for k in smoke["checkpoint_dirs"]),
        "reloads_and_acts": bool(reload_ok["action_finite"]),
        "device_batch_size": batch,
    }
    g_smoke["passes"] = bool(g_smoke["under_cap"] and g_smoke["weights_moved"]
                             and g_smoke["merged_checkpoint_written"] and g_smoke["reloads_and_acts"])
    bank.stage("g_smoke", g_smoke)
    bank.top("verdict", {"g_smoke": g_smoke, "g_grad": g_grad,
                         "d6_companion_agreement": None if d6 is None else
                         {k: d6[k] for k in ("median_spearman", "median_abs_shuffled_null", "passes")},
                         "gate_after_50_steps": reload_ok["gate_after_50_steps"],
                         "hours_per_1000_steps": (round(g_smoke["seconds_per_step"] * 1000 / 3600, 2)
                                                  if g_smoke.get("seconds_per_step") else None)})
    print(json.dumps(bank.payload["verdict"], indent=1, default=str), flush=True)


if __name__ == "__main__":
    sys.exit(main())
